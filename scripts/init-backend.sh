#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# Creates the Terraform remote-state backend (idempotent):
#   * S3 bucket   — versioned, SSE-S3 encrypted, public access blocked, TLS-only
#   * DynamoDB    — on-demand table with "LockID" hash key for state locking
# and writes terraform/backend.hcl for `terraform init -backend-config=backend.hcl`.
#
# Usage:
#   ./scripts/init-backend.sh [-r REGION] [-p PROJECT] [-e ENVIRONMENT]
# Environment overrides: AWS_REGION, PROJECT_NAME, ENVIRONMENT, AWS_PROFILE
# -----------------------------------------------------------------------------
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TF_DIR="$(cd "$SCRIPT_DIR/../terraform" && pwd)"

REGION="${AWS_REGION:-us-east-1}"
PROJECT="${PROJECT_NAME:-mtwa}"
ENVIRONMENT="${ENVIRONMENT:-dev}"

usage() {
  sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while getopts ":r:p:e:h" opt; do
  case "$opt" in
    r) REGION="$OPTARG" ;;
    p) PROJECT="$OPTARG" ;;
    e) ENVIRONMENT="$OPTARG" ;;
    h) usage 0 ;;
    *) usage 1 ;;
  esac
done

log() { printf '\033[1;34m[init-backend]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[init-backend] ERROR:\033[0m %s\n' "$*" >&2; exit 1; }

command -v aws >/dev/null 2>&1 || die "AWS CLI v2 is required (https://aws.amazon.com/cli/)."

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)" \
  || die "Unable to call STS. Configure credentials (aws configure / AWS_PROFILE)."

BUCKET="${PROJECT}-tfstate-${ACCOUNT_ID}-${REGION}"
TABLE="${PROJECT}-tflock"
STATE_KEY="${PROJECT}/${ENVIRONMENT}/terraform.tfstate"

log "Account:  $ACCOUNT_ID"
log "Region:   $REGION"
log "Bucket:   $BUCKET"
log "Table:    $TABLE"
log "Key:      $STATE_KEY"

# ------------------------------------------------------------- S3 bucket ----
if aws s3api head-bucket --bucket "$BUCKET" 2>/dev/null; then
  log "State bucket already exists."
else
  log "Creating state bucket..."
  if [ "$REGION" = "us-east-1" ]; then
    aws s3api create-bucket --bucket "$BUCKET" --region "$REGION" >/dev/null
  else
    aws s3api create-bucket --bucket "$BUCKET" --region "$REGION" \
      --create-bucket-configuration "LocationConstraint=$REGION" >/dev/null
  fi
  aws s3api wait bucket-exists --bucket "$BUCKET"
fi

aws s3api put-bucket-versioning --bucket "$BUCKET" \
  --versioning-configuration Status=Enabled

aws s3api put-bucket-encryption --bucket "$BUCKET" \
  --server-side-encryption-configuration \
  '{"Rules":[{"ApplyServerSideEncryptionByDefault":{"SSEAlgorithm":"AES256"},"BucketKeyEnabled":true}]}'

aws s3api put-public-access-block --bucket "$BUCKET" \
  --public-access-block-configuration \
  BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true

aws s3api put-bucket-policy --bucket "$BUCKET" --policy "$(cat <<JSON
{
  "Version": "2012-10-17",
  "Statement": [{
    "Sid": "DenyInsecureTransport",
    "Effect": "Deny",
    "Principal": "*",
    "Action": "s3:*",
    "Resource": ["arn:aws:s3:::$BUCKET", "arn:aws:s3:::$BUCKET/*"],
    "Condition": {"Bool": {"aws:SecureTransport": "false"}}
  }]
}
JSON
)"
log "State bucket configured (versioning, encryption, public access block, TLS-only)."

# --------------------------------------------------------- DynamoDB lock ----
if aws dynamodb describe-table --table-name "$TABLE" --region "$REGION" >/dev/null 2>&1; then
  log "Lock table already exists."
else
  log "Creating lock table..."
  aws dynamodb create-table \
    --table-name "$TABLE" \
    --region "$REGION" \
    --attribute-definitions AttributeName=LockID,AttributeType=S \
    --key-schema AttributeName=LockID,KeyType=HASH \
    --billing-mode PAY_PER_REQUEST \
    --sse-specification Enabled=true \
    --tags "Key=Project,Value=$PROJECT" "Key=ManagedBy,Value=init-backend.sh" >/dev/null
  aws dynamodb wait table-exists --table-name "$TABLE" --region "$REGION"
fi

# ------------------------------------------------------------ backend.hcl ----
cat > "$TF_DIR/backend.hcl" <<HCL
# Generated by scripts/init-backend.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
bucket         = "$BUCKET"
key            = "$STATE_KEY"
region         = "$REGION"
dynamodb_table = "$TABLE"
encrypt        = true
HCL

log "Wrote $TF_DIR/backend.hcl"
log "Next: cd terraform && terraform init -backend-config=backend.hcl"
